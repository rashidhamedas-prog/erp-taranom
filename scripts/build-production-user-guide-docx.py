BRAND = RGBColor(0x1B, 0x5C, 0x4A)
GOLD = RGBColor(0xC9, 0xA8, 0x4C)
DARK = RGBColor(0x1A, 0x1A, 0x1A)
MUTED = RGBColor(0x4A, 0x55, 0x54)
WHITE = RGBColor(0xFF, 0xFF, 0xFF)
FONT = "Tahoma"


def _set_run_font(run, size=11, bold=False, color=DARK, font=FONT):
    run.font.name = font
    run._element.rPr.rFonts.set(qn("w:eastAsia"), font)
    run._element.rPr.rFonts.set(qn("w:cs"), font)
    run.font.size = Pt(size)
    run.bold = bold
    run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rtl = OxmlElement("w:rtl")
    rPr.append(rtl)


def _rtl_p(p):
    pPr = p._p.get_or_add_pPr()
    bidi = OxmlElement("w:bidi")
    bidi.set(qn("w:val"), "1")
    pPr.append(bidi)
    jc = pPr.find(qn("w:jc"))
    if jc is None:
        jc = OxmlElement("w:jc")
        pPr.append(jc)
    jc.set(qn("w:val"), "right")
    p.paragraph_format.space_after = Pt(8)
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    p.paragraph_format.line_spacing = 1.28
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT


def _shade_cell(cell, fill):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tcPr.append(shd)


def _cell_border(cell):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = OxmlElement("w:tcMar")
    for edge, val in (("top", "80"), ("left", "100"), ("bottom", "80"), ("right", "100")):
        n = OxmlElement("w:" + edge)
        n.set(qn("w:w"), val)
        n.set(qn("w:type"), "dxa")
        tcMar.append(n)
    tcPr.append(tcMar)


def add_p(doc, text, size=11, bold=False, color=DARK, space_after=8, space_before=0):
    p = doc.add_paragraph()
    _rtl_p(p)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    run = p.add_run(text)
    _set_run_font(run, size=size, bold=bold, color=color)
    return p


def add_h(doc, text, level=1):
    p = doc.add_paragraph()
    _rtl_p(p)
    if level == 1:
        p.paragraph_format.space_before = Pt(22)
        p.paragraph_format.space_after = Pt(10)
        run = p.add_run(text)
        _set_run_font(run, size=18, bold=True, color=BRAND)
        # bottom border
        pPr = p._p.get_or_add_pPr()
        pBdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "12")
        bottom.set(qn("w:space"), "4")
        bottom.set(qn("w:color"), "1B5C4A")
        pBdr.append(bottom)
        pPr.append(pBdr)
    elif level == 2:
        p.paragraph_format.space_before = Pt(16)
        p.paragraph_format.space_after = Pt(8)
        run = p.add_run(text)
        _set_run_font(run, size=14, bold=True, color=RGBColor(0x2D, 0x7A, 0x5F))
    else:
        p.paragraph_format.space_before = Pt(12)
        p.paragraph_format.space_after = Pt(6)
        run = p.add_run(text)
        _set_run_font(run, size=12, bold=True, color=RGBColor(0x3D, 0x6B, 0x58))
    return p


def add_note(doc, text, kind="tip"):
    colors = {
        "tip": ("E8F5E9", "1B5C4A"),
        "warn": ("FFF8E1", "8D6E00"),
        "danger": ("FFEBEE", "C0392B"),
        "info": ("E3F2FD", "1565C0"),
    }
    fill, fg = colors[kind]
    table = doc.add_table(rows=1, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = table.cell(0, 0)
    _shade_cell(cell, fill)
    _cell_border(cell)
    p = cell.paragraphs[0]
    _rtl_p(p)
    p.paragraph_format.space_after = Pt(2)
    run = p.add_run(text)
    _set_run_font(run, size=10.5, bold=False, color=RGBColor(int(fg[0:2], 16), int(fg[2:4], 16), int(fg[4:6], 16)))
    doc.add_paragraph()


def add_table(doc, headers, rows):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    tbl = table._tbl
    tblPr = tbl.tblPr if tbl.tblPr is not None else OxmlElement("w:tblPr")
    bidi = OxmlElement("w:bidiVisual")
    bidi.set(qn("w:val"), "1")
    tblPr.append(bidi)
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        _shade_cell(cell, "1B5C4A")
        _cell_border(cell)
        p = cell.paragraphs[0]
        _rtl_p(p)
        p.paragraph_format.space_after = Pt(2)
        run = p.add_run(h)
        _set_run_font(run, size=10, bold=True, color=WHITE)
    for r_i, row in enumerate(rows):
        fill = "F7F9F8" if r_i % 2 == 0 else "FFFFFF"
        for c_i, val in enumerate(row):
            cell = table.rows[r_i + 1].cells[c_i]
            _shade_cell(cell, fill)
            _cell_border(cell)
            p = cell.paragraphs[0]
            _rtl_p(p)
            p.paragraph_format.space_after = Pt(2)
            run = p.add_run(str(val))
            _set_run_font(run, size=10, bold=False, color=DARK)
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_after = Pt(6)
    return table


def add_bullets(doc, items, numbered=False):
    for i, item in enumerate(items, 1):
        p = doc.add_paragraph()
        _rtl_p(p)
        p.paragraph_format.right_indent = Cm(0)
        p.paragraph_format.left_indent = Cm(0.2)
        prefix = f"{i}. " if numbered else "• "
        run = p.add_run(prefix + item)
        _set_run_font(run, size=11)


def set_doc_rtl(doc):
    for section in doc.sections:
        sectPr = section._sectPr
        bidi = OxmlElement("w:bidi")
        bidi.set(qn("w:val"), "1")
        sectPr.append(bidi)
        section.page_width = Cm(21.0)
        section.page_height = Cm(29.7)
        section.right_margin = Cm(1.8)
        section.left_margin = Cm(1.8)
        section.top_margin = Cm(1.6)
        section.bottom_margin = Cm(1.8)


def add_header_footer(doc):
    for section in doc.sections:
        header = section.header
        header.is_linked_to_previous = False
        hp = header.paragraphs[0]
        _rtl_p(hp)
        hp.paragraph_format.space_after = Pt(4)
        r1 = hp.add_run("پوشاک ترنم  |  آموزش کامل بخش تولید")
        _set_run_font(r1, size=9, bold=True, color=BRAND)
        pPr = hp._p.get_or_add_pPr()
        pBdr = OxmlElement("w:pBdr")
        bottom = OxmlElement("w:bottom")
        bottom.set(qn("w:val"), "single")
        bottom.set(qn("w:sz"), "8")
        bottom.set(qn("w:space"), "2")
        bottom.set(qn("w:color"), "C9A84C")
        pBdr.append(bottom)
        pPr.append(pBdr)

        footer = section.footer
        footer.is_linked_to_previous = False
        fp = footer.paragraphs[0]
        _rtl_p(fp)
        fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r2 = fp.add_run("ERP ترنم  ·  آموزش کارگاهی تولید  ·  صفحه ")
        _set_run_font(r2, size=9, color=MUTED)
        # PAGE field
        fld = OxmlElement("w:fldChar")
        fld.set(qn("w:fldCharType"), "begin")
        run = fp.add_run()
        run._r.append(fld)
        instr = OxmlElement("w:instrText")
        instr.set(qn("xml:space"), "preserve")
        instr.text = " PAGE "
        run2 = fp.add_run()
        run2._r.append(instr)
        _set_run_font(run2, size=9, color=MUTED)
        fld2 = OxmlElement("w:fldChar")
        fld2.set(qn("w:fldCharType"), "end")
        run3 = fp.add_run()
        run3._r.append(fld2)


